"""Build every asset the two screens need, plus screens/assets/manifest.js.

  python3 build_assets.py                 # three original demo albums
  python3 build_assets.py --no-api        # never call Claude, keyword fallback only

For each album: the 64x64 cover, two disc sprite sheets (LED background and transparent),
one backdrop per catalog scene recoloured from the cover, the UI colours for each, and the
scene the picker chose. The screens read it all from manifest.js (a plain script, so the
pages also work when opened straight from disk).
"""
import argparse
import json
import os

import backdrops as bd
import cover_to_cd as cc
import make_sprites as ms
from scene_picker import pick_scene

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, '..', 'screens', 'assets')

SPIN_SECONDS = 3          # one turn every 3 s (20 rpm), shared by both screens

# Original stand-in albums (fictional). In the app these come from Spotify at runtime.
DEMO = [
    dict(key='sunset', art=lambda u, v, x, y: ms.sunset_art(u, v, x, y), title='Slow Bloom', artist='Marlow Kei',
         album='Afterhours, Vol. 2', genres=['indie soul'], track='track 3 of 9', length=252, accent='#F29E4C'),
    dict(key='dusk', art=ms.dusk_art, title='Neon Tide', artist='Juniper Vale',
         album='Night Grid', genres=['synthwave'], track='track 1 of 11', length=228, accent='#E0607E'),
    dict(key='tide', art=cc.tide_art, title='Low Water', artist='The Amber Rooms',
         album='Shoreline', genres=['dream pop'], track='track 6 of 10', length=270, accent='#6FB3C0'),
]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--no-api', action='store_true')
    args = ap.parse_args()
    os.makedirs(ASSETS, exist_ok=True)
    manifest = {'spinSeconds': SPIN_SECONDS, 'frames': cc.FRAMES, 'scenes': list(bd.CATALOG), 'albums': []}
    for d in DEMO:
        k = d['key']
        cover = cc.render_cover(d['art'])
        cover.save(f'{ASSETS}/cover_{k}.png')
        cover_path = f'{ASSETS}/cover_{k}.png'
        cc.cd_sheet(cover).save(f'{ASSETS}/cd_led_{k}.png')
        cc.cd_sheet(cover, clear=True).save(f'{ASSETS}/cd_clear_{k}.png')
        theme = bd.theme_from_cover(cover)
        backdrops = {}
        for scene in bd.CATALOG:
            img, c = bd.render(scene, theme)
            img.save(f'{ASSETS}/bg_{k}_{scene}.png')
            backdrops[scene] = {'file': f'assets/bg_{k}_{scene}.png', 'on': c['ui_on'], 'off': c['ui_off'],
                                'shadow': c['shadow'], 'sky': c['sky_bot']}
        track = {'title': d['title'], 'artist': d['artist'], 'album': d['album'], 'genres': d['genres']}
        pick = pick_scene(track, cover_path, use_api=not args.no_api,
                          cache_path=os.path.join(HERE, 'scene_cache.json'))
        manifest['albums'].append({
            'key': k, 'title': d['title'], 'artist': d['artist'], 'album': d['album'], 'track': d['track'],
            'length': d['length'], 'accent': d['accent'],
            'discLed': f'assets/cd_led_{k}.png', 'discClear': f'assets/cd_clear_{k}.png',
            'scene': pick['scene'], 'sceneReason': pick['reason'], 'sceneSource': pick['source'],
            'backdrops': backdrops,
        })
        print(f'{k}: scene={pick["scene"]} ({pick["source"]})')
    with open(f'{ASSETS}/manifest.js', 'w') as f:
        f.write('// Generated by tools/build_assets.py\nwindow.TURNTABLE = ' + json.dumps(manifest, indent=2) + ';\n')
    print('wrote', os.path.normpath(ASSETS))


if __name__ == '__main__':
    main()
